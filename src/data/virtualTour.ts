/**
 * Cloudinary account that hosts the school's videos.
 * Override with NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME if it ever changes.
 */
export const CLOUDINARY_CLOUD_NAME =
  process.env.NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME ?? "dug0g6tli";

const cloudinaryVideoBase = () =>
  `https://res.cloudinary.com/${CLOUDINARY_CLOUD_NAME}/video/upload`;

const encodePublicId = (publicId: string) =>
  publicId.split("/").map(encodeURIComponent).join("/");

/**
 * Direct playable URLs for a Cloudinary video public ID. The first one is the
 * optimised delivery; if Cloudinary refuses it, the player falls back to the
 * untouched original. No videos are uploaded or duplicated.
 */
export function cloudinaryVideoSources(publicId: string): string[] {
  const id = encodePublicId(publicId);
  return [`${cloudinaryVideoBase()}/q_auto/${id}.mp4`, `${cloudinaryVideoBase()}/${id}.mp4`];
}

/** A still frame (taken at 2s) generated by Cloudinary from the same video. */
export function cloudinaryPosterUrl(publicId: string): string {
  return `${cloudinaryVideoBase()}/so_2,w_1280,h_720,c_fill,q_auto,f_jpg/${encodePublicId(publicId)}.jpg`;
}

